import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
const check = process.argv.includes("--check");
const defs = {};
for (const file of (await readdir("contracts/schemas")).sort())
  Object.assign(
    defs,
    JSON.parse(await readFile(`contracts/schemas/${file}`, "utf8")).$defs,
  );
const outputs = new Map();
const schemas = Object.fromEntries(
  Object.keys(defs).map((name) => [
    name,
    {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      ...defs[name],
      $defs: defs,
    },
  ]),
);
outputs.set(
  "packages/protocol/src/generated/schemas.ts",
  `// Generated by contracts:generate. Do not edit.\nconst definitions = ${JSON.stringify(defs, null, 2)};\nexport const schemas: Record<string, object> = Object.fromEntries(Object.entries(definitions).map(([name]) => [name, { $schema: "https://json-schema.org/draft/2020-12/schema", $ref: "#/$defs/" + name, $defs: definitions }]));\n`,
);
const exports = [];
for (const [name, def] of Object.entries(defs)) {
  const code = await compile({ ...def, $defs: defs }, name, {
    bannerComment: "/* Generated from contracts/schemas. Do not edit. */",
    unknownAny: true,
    unreachableDefinitions: false,
  });
  outputs.set(`packages/protocol/src/generated/${name}.ts`, code);
  exports.push(`export type { ${name} } from './generated/${name}.js';`);
}
outputs.set("packages/protocol/src/types.ts", exports.join("\n") + "\n");
outputs.set(
  "java/protocol/src/main/resources/contracts/schemas.json",
  JSON.stringify({ definitions: defs }, null, 2) + "\n",
);
const type = (p) =>
  p.const !== undefined
    ? typeof p.const === "number"
      ? "int"
      : typeof p.const === "boolean"
        ? "boolean"
        : "String"
    : p.type === "string"
      ? "String"
      : p.type === "integer"
        ? "Long"
        : p.type === "number"
          ? "Double"
          : p.type === "boolean"
            ? "Boolean"
            : "JsonNode";
const records = Object.entries(defs)
  .filter(([, d]) => d.type === "object")
  .map(
    ([name, d]) =>
      `    public record ${name}(${Object.entries(d.properties)
        .map(([k, p]) => `${type(p)} ${k}`)
        .join(", ")}) {}`,
  );
outputs.set(
  "java/protocol/src/main/java/dev/generative/equipment/protocol/Contracts.java",
  `// Generated from contracts/schemas. Do not edit.\npackage dev.generative.equipment.protocol;\nimport com.fasterxml.jackson.databind.JsonNode;\npublic final class Contracts {\n    private Contracts() {}\n${records.join("\n")}\n}\n`,
);
// OpenAPI 和派生类型一起生成，避免 HTTP 请求结构与运行时校验漂移。
const paths = {};
for (const route of JSON.parse(
  await readFile("contracts/http-routes.json", "utf8"),
)) {
  const parameters = [...route.path.matchAll(/\{([^}]+)\}/g)].map((m) => ({
    name: m[1],
    in: "path",
    required: true,
    schema: { type: "string" },
  }));
  if (route.method === "post" && route.path === "/v1/generations")
    parameters.push({
      name: "Idempotency-Key",
      in: "header",
      required: true,
      schema: { type: "string" },
    });
  const operation = {
    summary: route.summary,
    parameters,
    responses: {
      200: { description: "Success or idempotent replay" },
      400: { description: "Invalid request" },
      401: { description: "Authentication required" },
      404: { description: "Resource unavailable" },
      409: { description: "State or idempotency conflict" },
      422: { description: "Contract validation failed" },
      501: { description: "Not implemented in S0" },
      503: { description: "Dependency unavailable" },
    },
  };
  if (route.body)
    operation.requestBody = {
      required: true,
      content: {
        "application/json": {
          schema: { $ref: "#/components/schemas/" + route.body },
        },
      },
    };
  if (route.path === "/health/live") operation.security = [];
  if (route.method === "post" && route.path === "/v1/generations")
    operation.responses["202"] = {
      description: "Task persisted; not a generation success",
    };
  if (route.path.endsWith("capability-profiles"))
    operation.responses["201"] = { description: "Profile registered" };
  paths[route.path] ??= {};
  paths[route.path][route.method] = operation;
}
const openapi = {
  openapi: "3.1.0",
  info: { title: "Generative Equipment Service", version: "0.1.0" },
  servers: [{ url: "http://127.0.0.1:8765" }],
  security: [{ internalBearer: [] }],
  paths,
  components: {
    securitySchemes: { internalBearer: { type: "http", scheme: "bearer" } },
    schemas: JSON.parse(
      JSON.stringify(defs).replaceAll("#/$defs/", "#/components/schemas/"),
    ),
  },
};
const { stringify } = await import("yaml");
outputs.set("contracts/openapi.yaml", stringify(openapi));

let failed = false;
for (const [path, content] of outputs) {
  if (check) {
    if ((await readFile(path, "utf8").catch(() => null)) !== content) {
      console.error("Stale generated file:", path);
      failed = true;
    }
  } else {
    await mkdir(path.slice(0, path.lastIndexOf("/")), { recursive: true });
    await writeFile(path, content);
  }
}
if (failed) process.exitCode = 1;
else
  console.log(
    `${check ? "Checked" : "Generated"} ${outputs.size} contract artifacts.`,
  );
